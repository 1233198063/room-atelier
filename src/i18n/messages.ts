const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

/** Formats meters in the viewer's length unit, e.g. 0.55 → "55 cm" or "550 mm". */
export type Len = (m: number) => string;
/** Text that mentions a length is a function of the unit formatter. */
export type Described = string | ((len: Len) => string);
export const describe = (text: Described, len: Len) => (typeof text === "function" ? text(len) : text);

